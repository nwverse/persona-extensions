// Package voice tells the user's own words from everything else in a day of material: other people's messages,
// automated ones, the assistant's replies, and text an agent wrote and posted under the user's name (a pull request
// body Claude Code drafted, a commit message with a Co-Authored-By trailer). Only the user's own words are evidence of
// what the user thinks and how the user works; the rest is context.
//
// It also holds the one rule for "this line names the user": an @-mention of one of the user's names, or the user's
// real name in the text. Generic words the hub may list as a name ("用户", "我", "owner") never count: they are in
// half the messages of any group.
package voice

import (
	"regexp"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/nwverse/persona-extensions/extensions/enkeep-memory/internal/norm"
)

// Speakers the curator writes for lines that are not the user's own words.
const (
	// Ghost is a line under the user's name that an agent wrote (Generated with Claude Code, Co-Authored-By, …).
	Ghost = "我·代写"
	// AI is the assistant's side of a Persona conversation.
	AI = "助手"
)

// ghostMarks are the traces agents leave in text they write for a person. Case is ignored.
var ghostMarks = regexp.MustCompile(`(?i)generated with \[?(claude code|codex|cursor|copilot|aider|gemini)|` +
	`co-authored-by:[^\n]*(claude|anthropic|codex|openai|copilot|cursor|gemini|\[bot\]|noreply@)|` +
	`🤖 generated|generated by (claude|codex|copilot|an? ai)|` +
	`(drafted|written|posted) by (claude|codex|an? (ai|agent))|` +
	`由 ?(claude|codex|ai|agent|助手) ?(代写|生成|撰写|起草)|（?ai ?代写）?`)

// GhostWritten says whether a text carries an agent's trace: it is not the user's own words even when the user
// posted it.
func GhostWritten(body string) bool { return ghostMarks.MatchString(body) }

// Relabel gives a line the speaker it really has: the user's line that an agent wrote, that the user pasted from an
// assistant (Pasted), or that relays the user in the third person (Relayed: an assistant's words sent under the
// user's name), becomes Ghost.
func Relabel(l norm.Line) norm.Line {
	if l.Speaker == norm.Me && (GhostWritten(l.Body) || Pasted(l.Body) || Relayed(l.Body)) {
		l.Speaker = Ghost
	}
	return l
}

// AgentThread relabels the user's lines of a code-review or issue day that read as an agent's draft: agents that
// work for the user post pull requests, status updates and replies under the user's name, mostly without any trace,
// while the user's own review comments are short and plain. A line of the user's is taken as drafted when the thread
// already has a traced line of the user's that day, or when it is long (more than DraftedRunes), carries Markdown
// structure (two or more heading, list, table or code-fence lines), or follows an agent's status template.
func AgentThread(lines []norm.Line) []norm.Line {
	traced := slices.ContainsFunc(lines, func(l norm.Line) bool { return l.Speaker == Ghost })
	out := slices.Clone(lines)
	for i := range out {
		if out[i].Speaker == norm.Me && (traced || Drafted(out[i].Body)) {
			out[i].Speaker = Ghost
		}
	}
	return out
}

// DraftedRunes is the length past which a code-review comment of the user's is taken for an agent's draft.
const DraftedRunes = 300

var (
	markdownLine   = regexp.MustCompile(`(?m)^\s*(#{1,6} |[-*+] |\d+\. |\|.*\||` + "```" + `)`)
	statusTemplate = regexp.MustCompile(`(?mi)^\s*(agent|plan|eta|status|next steps?|summary|test plan|changes)\s*:`)
)

// Drafted says whether a code-review text reads as written by an agent rather than typed by a person.
func Drafted(body string) bool {
	return GhostWritten(body) || utf8.RuneCountInString(body) > DraftedRunes ||
		len(markdownLine.FindAllString(body, 3)) >= 2 || statusTemplate.MatchString(body)
}

// Own says whether a line is the user's own words.
func Own(l norm.Line) bool { return l.Speaker == norm.Me }

// IsAI says whether a speaker is the assistant of a Persona conversation.
func IsAI(speaker string) bool { return speaker == AI }

// generic are words that stand for "the user" in any message: the hub's default owner name and the like. They are
// never a name to look for.
var generic = []string{"用户", "我", "我自己", "自己", "本人", "主人", "机主", "老板", "你", "您", "owner", "user", "me", "myself",
	"self", "you", "admin", "the user", "the owner"}

// Generic says whether a name is one of the generic words for the user.
func Generic(name string) bool {
	q := norm.Q(name)
	return q == "" || slices.ContainsFunc(generic, func(g string) bool { return norm.Q(g) == q })
}

// Names drops the generic words from a list of the user's names.
func Names(names []string) []string {
	var out []string
	for _, n := range names {
		if n = strings.TrimSpace(n); n != "" && !Generic(n) && !slices.Contains(out, n) {
			out = append(out, n)
		}
	}
	return out
}

// Mentions says whether a text names the user: "@name" for any of the user's names, or a name written out in the
// text when it is distinctive (two or more Han characters, or four or more letters standing as a word). Generic
// words never count, whatever list they come in.
func Mentions(body string, names []string) bool {
	for _, n := range Names(names) {
		if strings.Contains(body, "@"+n) || strings.Contains(body, "@ "+n) {
			return true
		}
		if distinctive(n) && wordIn(body, n) {
			return true
		}
	}
	return false
}

func distinctive(n string) bool {
	han, letters := 0, 0
	for _, r := range n {
		switch {
		case unicode.Is(unicode.Han, r):
			han++
		case unicode.IsLetter(r):
			letters++
		}
	}
	return han >= 2 || (han == 0 && letters >= 4)
}

// wordIn finds name in body ignoring case; a name of letters must not be part of a longer word ("tom" in "tomato").
func wordIn(body, name string) bool {
	lb, ln := strings.ToLower(body), strings.ToLower(name)
	for i := 0; ; {
		j := strings.Index(lb[i:], ln)
		if j < 0 {
			return false
		}
		start, end := i+j, i+j+len(ln)
		before, _ := utf8.DecodeLastRuneInString(lb[:start])
		after, _ := utf8.DecodeRuneInString(lb[end:])
		if !latinWord(before) && !latinWord(after) || isHanName(ln) {
			return true
		}
		i = start + 1
	}
}

func latinWord(r rune) bool {
	return r != utf8.RuneError && (r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)) || r == '_')
}

func isHanName(n string) bool {
	for _, r := range n {
		if unicode.Is(unicode.Han, r) {
			return true
		}
	}
	return false
}

// Select picks the user's turns out of the shown lines: every line by the user, with up to before lines ahead of it
// (what the user answers) and after lines following it (how it was taken), by position among the shown lines. The
// lines that are not the user's are context only.
func Select(lines []norm.Line, shown map[int]bool, before, after int) map[int]bool {
	var vis []norm.Line
	for _, l := range lines {
		if shown[l.N] {
			vis = append(vis, l)
		}
	}
	out := map[int]bool{}
	for i, l := range vis {
		if !Own(l) {
			continue
		}
		for j := max(0, i-before); j <= min(len(vis)-1, i+after); j++ {
			out[vis[j].N] = true
		}
	}
	return out
}

// Count is the number of the user's own lines among the shown ones.
func Count(lines []norm.Line, shown map[int]bool) int {
	n := 0
	for _, l := range lines {
		if shown[l.N] && Own(l) {
			n++
		}
	}
	return n
}

// finance are the marks of a bank or payroll notification, or a statement of someone's money: balances, deposits,
// salary, card bills, transfers, vesting. Such text is never kept, whoever wrote it.
var finance = regexp.MustCompile(`(?i)余额|可用额度|入账|到账|工资|薪资|薪水|工资条|账单|信用卡|还款|转账|汇款|扣款|存款|理财|股权激励|期权归属|` +
	`\b(account )?balance\b|available balance|payslip|pay ?stub|paycheck|direct deposit|deposit(ed)?\b|statement (is )?ready|` +
	`credit card|minimum payment|wire transfer|\brsu\b|vest(ing|ed)?\b`)

// Finance says whether a text is about someone's money in the way a bank, payroll or broker notice is.
func Finance(text string) bool { return finance.MatchString(text) }

// automated are the marks of a sender that is not a person: bots, alerts, pushes, notices, system accounts.
var automated = regexp.MustCompile(`(?i)bot\b|机器人|助手|小秘书|通知|推送|播报|报警|告警|系统|alert|alarm|notif|noreply|no-reply|digest|oncall assistant|webhook`)

// Automated says whether a speaker is a program rather than a person, by its name.
func Automated(speaker string) bool { return speaker != norm.Me && automated.MatchString(speaker) }

// pasteFraming are the words an assistant frames a text with for the user to pass on ("下面这份可以直接转给她",
// "以下是整理好的…"): text the user forwards or pastes with them in it is the assistant's, not the user's.
var pasteFraming = regexp.MustCompile(`可以直接(转|发)给|下面这份|以下是(我)?(帮你|为你)?(整理|回复|草稿|改写|润色|生成)|文中的[“"]?我[”"]?是你|（?(由 ?)?AI ?(整理|生成|撰写)）`)

// sectioned are the lines that make a text a structured write-up: Markdown headings and lists, 【…】 headings, "一、"
// sections, **bold** spans.
var sectioned = regexp.MustCompile(`(?m)^\s*(#{1,6} |[-*+] |\d+[.、] |【[^】\n]{1,24}】|[一二三四五六七八九十]+、)|\*\*[^*\n]+\*\*`)

// PastedRunes is the length past which a message of the user's is looked at as possibly pasted.
const PastedRunes = 200

// Pasted says whether a long chat message of the user's is an assistant's text the user forwarded or pasted: it is
// framed for passing on, or it is a structured write-up (three or more headings, sections or list items). A long
// message the user typed or dictated, without either, stays the user's.
func Pasted(body string) bool {
	if utf8.RuneCountInString(body) <= PastedRunes {
		return false
	}
	return pasteFraming.MatchString(body) || len(sectioned.FindAllString(body, 4)) >= 3
}

// Roles of a line, as an item's or an entry's evidence records them.
const (
	RoleUser       = "user"        // the user's own words
	RoleAssistant  = "assistant"   // the Persona assistant's reply
	RoleAgentDraft = "agent_draft" // under the user's name, but written by an agent or pasted from one
	RoleBot        = "bot"         // an automated sender: bots, alerts, pushes
	RoleOther      = "other"       // another person
)

// Role is who a line is by. kind is the chat's kind: in a bot chat everyone but the user is the bot.
func Role(l norm.Line, kind string) string {
	switch {
	case l.Speaker == norm.Me:
		return RoleUser
	case l.Speaker == Ghost:
		return RoleAgentDraft
	case l.Speaker == AI:
		return RoleAssistant
	case kind == "bot" || Automated(l.Speaker):
		return RoleBot
	}
	return RoleOther
}

// Source says whether a line of this role can be what an entry about the user rests on: the user's words, or
// another person's. The assistant, an agent's draft and a bot are context only.
func Source(role string) bool { return role == RoleUser || role == RoleOther }

// agreement is a reply that only goes along with what was said before it.
var agreement = regexp.MustCompile(`^(好|好的|好滴|好嘞|好吧|行|行吧|可以|对|对的|对对|是|是的|嗯+|恩+|哦+|收到|同意|赞|没问题|就这样|就这么办|ok|okay|okk|lgtm|yes|yep|sure|thanks|谢谢|多谢)+$`)

// Agreement says whether a quote is only agreement ("好", "对", "就这样", "LGTM"): it supports nothing of its own,
// so whatever it agrees to is whoever said that.
func Agreement(quote string) bool {
	q := norm.Q(quote)
	return q == "" || agreement.MatchString(q)
}

// relayed are the ways an assistant passes the user on to an agent or a person: "用户要求你…", "按用户的交代…",
// "替用户…", "以用户名义…". The user does not speak of themselves so; "用户反馈加载慢" (a product's users) does not
// match.
var relayed = regexp.MustCompile(`用户(之前|已经|刚才|本人)?(要求|让|希望|交代|说过|同意|授权|吩咐)(了)?你|按用户(的)?(要求|交代|意思|指示)|替用户|代用户|以用户(的)?名义|用户本人(要求|说|同意|决定)`)

// Relayed says whether a text speaks of the user in the third person to someone it works for: an assistant's words,
// whoever posted them.
func Relayed(body string) bool { return relayed.MatchString(body) }
